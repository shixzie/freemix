//! Message keys with their compiled-in English text.
//!
//! Each line declares one [`Msg`] key and its English entry: `t("…")` for
//! a plain template, `plural("…one…", "…other…")` for a message whose form
//! follows its `{count}` argument. English is complete by construction;
//! other catalogs are checked against this list by unit test.

use super::{Entry, plural, t};

macro_rules! messages {
    ($($key:ident => $entry:expr,)*) => {
        /// A typed message key. The English text lives beside each key; see
        /// [`super::Locale::text`] and [`super::Locale::format`].
        #[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]
        pub enum Msg {
            $($key,)*
        }

        impl Msg {
            /// Every key, in declaration order.
            pub const ALL: &'static [Self] = &[$(Self::$key,)*];

            /// The key's name, for diagnostics and catalog reports.
            #[must_use]
            pub const fn id(self) -> &'static str {
                match self {
                    $(Self::$key => stringify!($key),)*
                }
            }

            /// The compiled-in English entry.
            #[must_use]
            pub const fn source(self) -> Entry {
                match self {
                    $(Self::$key => $entry,)*
                }
            }
        }
    };
}

impl Msg {
    /// The English text (the `other` form of a plural). Code that threads
    /// operator text as `&'static str` produces it with this, and drawing
    /// code words it in the console language with
    /// [`super::Locale::tr`].
    #[must_use]
    pub const fn en(self) -> &'static str {
        self.source().other()
    }

    /// The sentence for an animation editor refusal, keyed by its stable
    /// id ([`crate::animation_editor::AnimEditorError::msg_key`]); `None`
    /// for an id this catalog does not know yet.
    #[must_use]
    pub fn anim_editor_error(msg_key: &str) -> Option<Self> {
        Some(match msg_key {
            "anim-editor-retime-collision" => Self::AnimErrRetimeCollision,
            "anim-editor-key-collision" => Self::AnimErrKeyCollision,
            "anim-editor-limit-exceeded" => Self::AnimErrLimitExceeded,
            "anim-editor-key-outside-phase" => Self::AnimErrKeyOutsidePhase,
            "anim-editor-invalid-value" => Self::AnimErrInvalidValue,
            "anim-editor-unknown-key" => Self::AnimErrUnknownKey,
            "anim-editor-unknown-target" => Self::AnimErrUnknownTarget,
            "anim-editor-zero-span" => Self::AnimErrZeroSpan,
            "anim-editor-empty-selection" => Self::AnimErrEmptySelection,
            "anim-editor-too-few-targets" => Self::AnimErrTooFewTargets,
            "anim-editor-empty-clipboard" => Self::AnimErrEmptyClipboard,
            "anim-editor-no-drag" => Self::AnimErrNoDrag,
            "anim-editor-drag-active" => Self::AnimErrDragActive,
            "anim-editor-nothing-to-undo" => Self::AnimErrNothingToUndo,
            "anim-editor-nothing-to-redo" => Self::AnimErrNothingToRedo,
            "anim-editor-invalid-clip" => Self::AnimErrInvalidClip,
            "anim-editor-no-segment" => Self::AnimErrNoSegment,
            _ => return None,
        })
    }
}

